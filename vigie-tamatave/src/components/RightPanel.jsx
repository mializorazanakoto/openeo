import React, { useState } from 'react';
import { X, FileText, Anchor, ShieldAlert, Crosshair, Download, Navigation } from 'lucide-react';
import jsPDF from 'jspdf';

const RightPanel = ({ ship, onClose }) => {
  const [showDispatchModal, setShowDispatchModal] = useState(false);

  if (!ship) return null;

  const handleGenerateReport = () => {
    const doc = new jsPDF();

    // Header
    // doc.setFillColor(13, 17, 23);
    doc.setFontSize(22);
    doc.setTextColor(40, 40, 40);
    doc.text("OFFICIAL EVIDENCE REPORT", 20, 20);

    doc.setFontSize(12);
    doc.setTextColor(100, 100, 100);
    doc.text(`Reference: REF-${ship.id}-${Date.now()}`, 20, 30);

    // Line
    doc.setLineWidth(0.5);
    doc.line(20, 35, 190, 35);

    // Ship Details
    doc.setFontSize(14);
    doc.setTextColor(0, 0, 0);
    doc.text("VESSEL DETAILS", 20, 45);

    doc.setFontSize(10);
    doc.text(`Vessel ID: ${ship.id}`, 20, 55);
    doc.text(`Type: ${ship.type}`, 20, 60);
    doc.text(`Coordinates: ${ship.lat}, ${ship.lng}`, 20, 65);
    doc.text(`Speed: ${ship.speed} knots`, 20, 70);
    doc.text(`Heading: ${ship.heading}`, 20, 75);

    if (ship.status === 'illegal') {
      doc.setTextColor(200, 0, 0);
      doc.text(`ALERT STATUS: ILLEGAL ACTIVITY DETECTED`, 20, 85);
      doc.text(`AI CONFIDENCE: ${ship.confidence}%`, 20, 90);
    } else {
      doc.setTextColor(0, 150, 0);
      doc.text(`STATUS: LEGAL`, 20, 85);
    }

    // Footer
    doc.setTextColor(150, 150, 150);
    doc.text("Generated by VIGIE TAMATAVE System", 20, 280);

    doc.save(`Evidence_Report_${ship.id}.pdf`);
  };

  const handleDispatch = () => {
    setShowDispatchModal(true);
    setTimeout(() => setShowDispatchModal(false), 5000);
  };

  return (
    <div className="w-96 h-full bg-[#161b22] border-l border-[#30363d] flex flex-col z-20 shadow-2xl relative">
       {/* Modal/Toast Overlay - Positioned relative to panel but visualised on map usually, here fixed to show properly */}
       {showDispatchModal && (
         <div className="fixed top-10 right-[400px] z-[9999] pointer-events-none">
            <div className="bg-green-600 text-white px-6 py-4 rounded shadow-2xl border border-green-400 flex items-center gap-4 animate-bounce">
               <ShieldAlert size={32} className="animate-pulse" />
               <div>
                 <h4 className="font-bold text-lg">DISPATCH SENT</h4>
                 <p className="text-sm">Interceptor vessel ATSINANANA deployed.</p>
                 <p className="text-xs opacity-80 mt-1">ETA: 45 Minutes</p>
               </div>
            </div>
         </div>
       )}

      {/* Header */}
      <div className="p-4 border-b border-[#30363d] flex justify-between items-center bg-[#0d1117]">
        <h2 className="text-lg font-bold text-white tracking-wider flex items-center gap-2">
           <Crosshair size={20} className={ship.status === 'illegal' ? 'text-[#da3633]' : 'text-green-500'} />
           TARGET ANALYSIS
        </h2>
        <button onClick={onClose} className="text-gray-400 hover:text-white transition-colors">
          <X size={20} />
        </button>
      </div>

      {/* Content */}
      <div className="flex-1 overflow-y-auto p-4 space-y-6 custom-scrollbar">
        {/* Image */}
        <div className="relative rounded-lg overflow-hidden border border-[#30363d] h-48 group">
          <img
            src={ship.image || "https://images.unsplash.com/photo-1542345091-a151b1479867?ixlib=rb-1.2.1&auto=format&fit=crop&w=800&q=80"}
            alt="Vessel"
            className="w-full h-full object-cover opacity-80 group-hover:opacity-100 transition-opacity"
          />
          <div className="absolute bottom-0 left-0 right-0 bg-gradient-to-t from-black/90 to-transparent p-3">
             <div className="flex justify-between items-end">
               <span className="text-xs font-mono text-[#58a6ff]">OPTICAL SAT-FEED</span>
               <span className="text-[10px] text-gray-400 uppercase">Live - 30s ago</span>
             </div>
          </div>
          {/* Target Box Overlay */}
          <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-16 h-16 border-2 border-[#da3633]/50 rounded-full flex items-center justify-center animate-pulse">
             <div className="w-1 h-1 bg-[#da3633]"></div>
          </div>
        </div>

        {/* Info Grid */}
        <div className="grid grid-cols-2 gap-3">
           <div className="bg-[#0d1117] p-3 rounded border border-[#30363d]">
              <span className="text-[10px] uppercase text-gray-500 block mb-1">Vessel ID</span>
              <span className="text-sm font-mono text-white font-bold">{ship.id}</span>
           </div>
           <div className="bg-[#0d1117] p-3 rounded border border-[#30363d]">
              <span className="text-[10px] uppercase text-gray-500 block mb-1">Type</span>
              <span className="text-sm font-mono text-white">{ship.type}</span>
           </div>
           <div className="bg-[#0d1117] p-3 rounded border border-[#30363d]">
              <span className="text-[10px] uppercase text-gray-500 block mb-1">Speed / Heading</span>
              <span className="text-sm font-mono text-white">{ship.speed}kn / {ship.heading}</span>
           </div>
           <div className="bg-[#0d1117] p-3 rounded border border-[#30363d]">
              <span className="text-[10px] uppercase text-gray-500 block mb-1">Classification</span>
              <span className={`text-sm font-mono font-bold ${ship.status === 'illegal' ? 'text-[#da3633]' : 'text-green-500'}`}>
                {ship.status === 'illegal' ? 'HOSTILE' : 'NEUTRAL'}
              </span>
           </div>
        </div>

        {/* AI Analysis */}
        {ship.status === 'illegal' && (
          <div className="bg-[#da3633]/10 border border-[#da3633]/30 p-4 rounded">
            <h3 className="text-[#da3633] text-xs font-bold uppercase tracking-wider mb-2 flex items-center gap-2">
               <ShieldAlert size={14} />
               Threat Detected
            </h3>
            <div className="space-y-2">
               <div className="flex justify-between text-xs text-gray-300">
                 <span>Dark Vessel Probability</span>
                 <span className="text-white font-mono">{ship.confidence}%</span>
               </div>
               <div className="w-full bg-[#0d1117] h-1.5 rounded-full overflow-hidden">
                 <div className="h-full bg-[#da3633]" style={{ width: `${ship.confidence}%` }}></div>
               </div>
               <p className="text-[10px] text-gray-400 mt-2 leading-relaxed">
                 Vessel AIS transponder is inactive. Trajectory matches known illegal fishing patterns in protected zone.
               </p>
            </div>
          </div>
        )}

      </div>

      {/* Action Footer */}
      <div className="p-4 border-t border-[#30363d] bg-[#0d1117] space-y-3">
        <button
          onClick={handleGenerateReport}
          className="w-full py-2.5 px-4 rounded bg-[#161b22] border border-[#30363d] text-gray-300 text-sm font-medium hover:bg-[#30363d] hover:text-white transition-colors flex items-center justify-center gap-2 cursor-pointer"
        >
          <FileText size={16} />
          Generate Evidence Report
        </button>

        <button
          onClick={handleDispatch}
          className="w-full py-3 px-4 rounded bg-[#da3633] hover:bg-[#b52a27] text-white text-sm font-bold tracking-wide transition-colors shadow-lg shadow-red-900/20 flex items-center justify-center gap-2 cursor-pointer"
        >
          <Navigation size={16} />
          DISPATCH COAST GUARD
        </button>
      </div>
    </div>
  );
};

export default RightPanel;
